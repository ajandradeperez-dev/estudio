const norm=t=>String(t).toLowerCase().normalize('NFD').replace(/\p{Diacritic}/gu,'').trim();
const INDICE=new Map(Object.entries(G).map(([k,v])=>[norm(k),{palabra:k,significado:v}]));
// Definición de una palabra (o de una expresión de la frase que la contiene)
export function definicion(palabra,frase=''){
  const w=norm(palabra),f=norm(frase);
  for(const [k,v] of INDICE)if(k.includes(' ')&&k.split(' ').includes(w)&&f.includes(k))return v;
  const variantes=[w,w.replace(/es$/,''),w.replace(/s$/,''),w.replace(/(me|te|se|le|les|lo|la|los|las|nos)$/,'')];
  for(const x of variantes)if(INDICE.has(x))return INDICE.get(x);
  return null;
}
